const dictionaries = { en, ru: ruDict } as const
const dateLocales = { en: enUS, ru } as const

export type Locale = keyof typeof dictionaries

export function resolveLocale(language: Language): Locale {
  if (language !== 'auto') return language
  const nav = typeof navigator !== 'undefined' ? navigator.language : 'en'
  return nav.toLowerCase().startsWith('ru') ? 'ru' : 'en'
}

let current: Locale = resolveLocale('auto')

/** Set by App on every render from settings, before children render. */
export function setLocale(locale: Locale) {
  current = locale
  if (typeof document !== 'undefined') document.documentElement.lang = locale
}

export const getLocale = () => current

export function t(key: Key, params?: Record<string, string | number>): string {
  let s: string = dictionaries[current][key] ?? en[key]
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}

/** date-fns format in the current locale. */
/** Short weekday name: "Mon" / "пн" (date-fns ru 'EEE' gives three letters). */
export const fmtWeekday = (date: Date) => fmt(date, current === 'ru' ? 'EEEEEE' : 'EEE')

export function fmt(date: Date, pattern: string): string {
  return formatDate(date, pattern, { locale: dateLocales[current] })
}
